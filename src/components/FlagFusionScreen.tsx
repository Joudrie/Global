interface Played { fusion: Fusion; solved: Part[]; wrongLeft: number; points: number }
interface Game { id: number; tier: Tier; fusions: Fusion[] }
interface Outcome { played: Played[]; best: number; beat: boolean }
const scoreOf = (played: Played[]) => played.reduce((s, p) => s + p.points, 0)

export default function FlagFusionScreen({ onBack, onFinish }: { onBack: () => void; onFinish?: () => void }) {
  const [game, setGame] = useState<Game | null>(null)
  const [outcome, setOutcome] = useState<Outcome | null>(null)
  const [helpOpen, setHelpOpen] = useState(false)

  const begin = (tier: Tier) => {
    write(PREFS_KEY, { tier })
    setOutcome(null)
    setGame(g => ({ id: (g?.id ?? 0) + 1, tier, fusions: dealGame(tier) }))
    window.scrollTo({ top: 0 })
  }
  const finish = (g: Game, played: Played[]) => {
    const all = loadBest()
    const prev = all[g.tier]
    const score = scoreOf(played)
    if (prev === undefined || score > prev) write(BEST_KEY, { ...all, [g.tier]: score })
    setOutcome({ played, best: Math.max(prev ?? 0, score), beat: prev !== undefined && score > prev })
    onFinish?.()
    window.scrollTo({ top: 0 })
  }
  const help = <HelpButton onClick={() => setHelpOpen(true)} />

  return (
    <div className="min-h-screen flex flex-col" style={{ background: T.bg, color: T.text }}>
      <style>{STYLES}</style>
      {!game && <Start onStart={begin} onBack={onBack} help={help} />}
      {game && !outcome && <Play key={game.id} game={game} onBack={onBack} help={help} onDone={p => finish(game, p)} />}
      {game && outcome && <Result game={game} outcome={outcome} onBack={onBack}
        onAgain={() => begin(game.tier)} onChange={() => { setGame(null); setOutcome(null) }} />}
      <HowItWorks open={helpOpen} onClose={() => setHelpOpen(false)} />
    </div>
  )
}

