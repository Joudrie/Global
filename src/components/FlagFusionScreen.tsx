/* ── The emblem stencils, fetched once per game. ───────────────────────── */
const stencilCache = new Map<string, string>()
function useStencils(codes: string[]) {
  const key = codes.join()
  const [state, setState] = useState<{ ready: boolean; failed: boolean; tick: number }>(() =>
    ({ ready: codes.every(c => stencilCache.has(c)), failed: false, tick: 0 }))
  useEffect(() => {
    let live = true
    const missing = [...new Set(codes)].filter(c => !stencilCache.has(c))
    if (!missing.length) { setState(s => ({ ...s, ready: true, failed: false })); return }
    setState(s => ({ ...s, ready: false, failed: false }))
    Promise.all(missing.map(c => fetch(emblemUrl(c)).then(r => {
      if (!r.ok) throw new Error(String(r.status))
      return r.text()
    }).then(t => { if (!t.includes("ff-stencil")) throw new Error("not a stencil"); stencilCache.set(c, t) })))
      .then(() => { if (live) setState(s => ({ ...s, ready: true })) })
      .catch(() => { if (live) setState(s => ({ ...s, failed: true })) })
    return () => { live = false }
  }, [key, state.tick]) // codes is a fresh array each render; key stands for it
  return { ready: state.ready, failed: state.failed, retry: () => setState(s => ({ ...s, tick: s.tick + 1 })) }
}

/** The fused flag as one image. Its colours and parts are the puzzle, so the
 *  label says nothing about them. */
function FusedFlag({ fusion, label = "The fused flag", style }: { fusion: Fusion; label?: string; style?: CSSProperties }) {
  const stencil = stencilCache.get(fusion.emblem.code)
  const src = useMemo(() => (stencil ? svgUri(fusionSvg(fusion, stencil)) : null), [fusion, stencil])
  return (
    <div role="img" aria-label={label}
      style={{ position: "relative", aspectRatio: "4 / 3", width: "100%", borderRadius: 4, overflow: "hidden", background: T.surfaceHi,
        border: `1px solid ${T.line}`, boxShadow: `0 8px 24px -14px ${tint(T.text, 0.55)}`, ...style }}>
      {src && <img src={src} alt="" draggable={false} style={{ position: "absolute", inset: 0, width: "100%", height: "100%", display: "block" }} />}
    </div>
  )
}

/* ── A game: five fused flags, then the result. ─────────────────────────── */
interface Box { pick: FlagRecord | null; locked: boolean; flash: FlagRecord | null; tried: string[] }
const emptyBoxes = (): Record<Part, Box> => ({
  structure: { pick: null, locked: false, flash: null, tried: [] },
  emblem: { pick: null, locked: false, flash: null, tried: [] },
  colours: { pick: null, locked: false, flash: null, tried: [] },
})

function Play({ game, onBack, onDone, help }: { game: Game; onBack: () => void; onDone: (p: Played[]) => void; help: ReactNode }) {
  const { tier, fusions } = game
  const stencils = useStencils(fusions.map(f => f.emblem.code))
  const [idx, setIdx] = useState(0)
  const [boxes, setBoxes] = useState(emptyBoxes)
  const [wrongLeft, setWrongLeft] = useState(WRONG_GUESSES)
  const [played, setPlayed] = useState<Played[]>([])
  const [said, setSaid] = useState("")          // the live region's last message
  const flashTimer = useRef<ReturnType<typeof setTimeout> | null>(null)
  const nextWrap = useRef<HTMLDivElement>(null)
  useEffect(() => () => { if (flashTimer.current) clearTimeout(flashTimer.current) }, [])

  const f = fusions[idx]
  const result = played[idx] as Played | undefined
  const over = !!result
  const score = scoreOf(played)
  const last = idx + 1 >= fusions.length
  const canGuess = !over && PARTS.some(p => !boxes[p].locked && boxes[p].pick && !boxes[p].flash)

  useEffect(() => { if (over) nextWrap.current?.querySelector("button")?.focus({ preventScroll: true }) }, [over])

  const setPick = (part: Part, pick: FlagRecord | null) => setBoxes(b => ({ ...b, [part]: { ...b[part], pick } }))

  const guess = () => {
    if (!canGuess) return
    const next = { ...boxes }
    const wrongParts: Part[] = []
    const rightParts: Part[] = []
    for (const p of PARTS) {
      const b = next[p]
      if (b.locked || !b.pick) continue
      if (isRight(f, p, b.pick.code)) { next[p] = { ...b, locked: true, flash: null }; rightParts.push(p) }
      else { next[p] = { ...b, pick: null, flash: b.pick, tried: [...b.tried, b.pick.code] }; wrongParts.push(p) }
    }
    const left = Math.max(0, wrongLeft - wrongParts.length)
    const solved = PARTS.filter(p => next[p].locked)
    const won = solved.length === PARTS.length
    const lost = !won && left === 0
    setBoxes(next)
    setWrongLeft(left)
    const bits = [
      ...rightParts.map(p => `${PART_LABEL[p]} right: ${countryName(next[p].pick!.code)}.`),
      ...wrongParts.map(p => `${PART_LABEL[p]} wrong.`),
    ]
    if (won || lost) {
      const points = fusionPoints(solved.length, left)
      setPlayed(pl => [...pl, { fusion: f, solved, wrongLeft: left, points }])
      setSaid(`${bits.join(" ")} ${won ? `All three named: plus ${points} points.` : `Out of wrong guesses: plus ${points} points.`} It was ${countryName(f.structure.code)}, ${countryName(f.emblem.code)} and ${countryName(f.colours.code)}.`)
    } else {
      setSaid(`${bits.join(" ")} ${left} wrong ${left === 1 ? "guess" : "guesses"} left.`)
    }
    if (wrongParts.length) {
      if (flashTimer.current) clearTimeout(flashTimer.current)
      flashTimer.current = setTimeout(() => setBoxes(b => {
        const out = { ...b }
        for (const p of PARTS) out[p] = { ...out[p], flash: null }
        return out
      }), FLASH_MS)
    }
  }

  const next = () => {
    if (!over) return
    if (last) { onDone(played); return }
    if (flashTimer.current) clearTimeout(flashTimer.current)
    setIdx(i => i + 1)
    setBoxes(emptyBoxes())
    setWrongLeft(WRONG_GUESSES)
    setSaid("")
    window.scrollTo({ top: 0 })
  }

  if (stencils.failed) {
    return (
      <>
        <ScreenHeader title="Flag Fusion" onBack={onBack} />
        <main className="w-full mx-auto flex flex-col items-center" style={{ maxWidth: 720, padding: "12px 16px 32px" }}>
          <FlagLoadFailed onRetry={stencils.retry} onBack={onBack} accent={ACC} />
        </main>
      </>
    )
  }

  return (
    <>
      <ScreenHeader title="Flag Fusion" subtitle={`${TIER_META[tier].label} · ${idx + 1}/${fusions.length} · ${score} pts`} onBack={onBack} right={help} />
      <div aria-live="polite" style={srOnly}>{said}</div>
      <main className="w-full mx-auto flex flex-col" style={{ maxWidth: 520, padding: "4px 16px 32px", gap: 12 }}>
        <div key={idx} className="ff-in" aria-busy={!stencils.ready || undefined}>
          {stencils.ready
            ? <FusedFlag fusion={f} />
            : <div role="status" style={{ aspectRatio: "4 / 3", width: "100%", borderRadius: 4, border: `1px solid ${T.line}`, background: T.surfaceHi,
                display: "flex", alignItems: "center", justifyContent: "center", color: T.muted, fontSize: 14 }}>Fusing the flag…</div>}
        </div>

        <div role="group" aria-label="Name the three countries" style={{ display: "flex", flexDirection: "column", gap: 8 }}>
          {PARTS.map(p => (
            <PartBox key={`${idx}-${p}`} part={p} box={boxes[p]} fusion={f} over={over}
              onPick={c => setPick(p, c)} onSubmit={guess} />
          ))}
        </div>

        {!over ? (
          <>
            <WrongDots left={wrongLeft} />
            <PrimaryButton accent={ACC} disabled={!canGuess} onClick={guess}>Guess</PrimaryButton>
          </>
        ) : (
          <Reveal fusion={f} result={result} />
        )}
        {over && (
          <div ref={nextWrap}>
            <PrimaryButton accent={ACC} onClick={next}>{last ? "See results" : "Next flag"}</PrimaryButton>
          </div>
        )}
      </main>
    </>
  )
}

/* ── "5 wrong guesses left" as five dots: filled while unused. ──────────── */
