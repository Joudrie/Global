/* ── One box: a type-ahead country picker, then a chip; green once right. ── */
const PART_HINT: Record<Part, string> = { structure: "the layout", emblem: "the symbol", colours: "the paint" }

function PartBox({ part, box, fusion, over, onPick, onSubmit }:
  { part: Part; box: Box; fusion: Fusion; over: boolean; onPick: (c: FlagRecord | null) => void; onSubmit: () => void }) {
  const [typed, setTyped] = useState("")
  const [focused, setFocused] = useState(false)
  const [active, setActive] = useState(-1) // the option picked out with the arrow keys
  const [maybe, setMaybe] = useState<FlagRecord[]>([]) // "Did you mean …?" after Enter on a typo
  const inputRef = useRef<HTMLInputElement>(null)
  const id = `ff-${part}`
  const options = useMemo(() => matchNames(FLAGS.filter(c => !box.tried.includes(c.code)), typed, 5), [typed, box.tried])
  useEffect(() => setActive(-1), [typed])

  const choose = useCallback((c: FlagRecord) => { onPick(c); setTyped(""); setMaybe([]); setFocused(false); inputRef.current?.blur() }, [onPick])
  const onKey = (e: ReactKeyboardEvent<HTMLInputElement>) => {
    if (e.key === "ArrowDown" && options.length) { e.preventDefault(); setActive(a => (a + 1) % options.length) }
    else if (e.key === "ArrowUp" && options.length) { e.preventDefault(); setActive(a => (a <= 0 ? options.length : a) - 1) }
    else if (e.key === "Enter") {
      e.preventDefault()
      // Enter in an empty box guesses, so a keyboard player can fill several
      // boxes and send them together.
      if (!typed.trim()) { onSubmit(); return }
      // An exact name or the only match (never a guess), or the option the
      // arrow keys picked out.
      const pick = pickOnEnter(options, typed) ?? (active >= 0 ? options[active] : undefined)
      if (pick) choose(pick)
      else if (!options.length) setMaybe(didYouMean(FLAGS, typed).filter(c => !box.tried.includes(c.code)))
    } else if (e.key === "Escape") { setTyped(""); setMaybe([]); setFocused(false) }
  }

  const answer = fusion[part].code
  const state = box.locked ? "right" : box.flash ? "wrong" : over ? "missed" : "open"
  const color = state === "right" ? T.green : state === "wrong" || state === "missed" ? T.danger : null
  const showList = focused && typed.trim() !== "" && options.length > 0 && state === "open" && !box.pick

  return (
    <div className="ff-box" style={{ borderRadius: 12, padding: 8, background: color ? tint(color, 0.08) : T.surface,
      border: `1.5px solid ${color ?? (box.pick ? tint(ACC, 0.5) : T.line)}` }}>
      <div style={{ display: "flex", alignItems: "center", gap: 8, minHeight: 44 }}>
        <label htmlFor={id} style={{ width: 92, flexShrink: 0, paddingLeft: 4, display: "flex", flexDirection: "column", lineHeight: 1.15 }}>
          <span className="geo-display" style={{ fontSize: 16, fontWeight: 700, color: color ?? T.text }}>{PART_LABEL[part]}</span>
          <span style={{ fontSize: 11, color: T.muted }}>{PART_HINT[part]}</span>
        </label>
        <div style={{ flex: 1, minWidth: 0 }}>
          {state === "right" || state === "missed" ? (
            <div style={{ display: "flex", alignItems: "center", gap: 8, minHeight: 44, color: state === "right" ? T.green : T.text }}>
              {state === "right" ? <Check size={18} strokeWidth={2.4} aria-hidden /> : <X size={18} strokeWidth={2.4} aria-hidden color={T.danger} />}
              <span style={{ fontSize: 15, fontWeight: 700, overflowWrap: "anywhere" }}>
                {state === "right" ? countryName(box.pick!.code) : <><span style={srOnly}>Not named. It was </span>{countryName(answer)}</>}
              </span>
            </div>
          ) : state === "wrong" ? (
            <div className="ff-fade" style={{ display: "flex", alignItems: "center", gap: 8, minHeight: 44, color: T.danger }}>
              <X size={18} strokeWidth={2.4} aria-hidden />
              <span style={{ fontSize: 15, fontWeight: 700, textDecoration: "line-through", overflowWrap: "anywhere" }}>{countryName(box.flash!.code)}</span>
            </div>
          ) : box.pick ? (
            <div style={{ display: "flex", alignItems: "center", gap: 8, minHeight: 44 }}>
              <span style={{ flex: 1, minWidth: 0, fontSize: 15, fontWeight: 700, color: T.text, overflowWrap: "anywhere" }}>{countryName(box.pick.code)}</span>
              <button type="button" onClick={() => { onPick(null); requestAnimationFrame(() => inputRef.current?.focus()) }}
                aria-label={`Clear ${PART_LABEL[part]}`} className="ff-tap ff-clear"
                style={{ width: 44, height: 44, borderRadius: 999, flexShrink: 0, display: "grid", placeItems: "center", cursor: "pointer",
                  background: T.surface, border: `1px solid ${T.line}`, color: T.muted }}>
                <X size={16} strokeWidth={2} aria-hidden />
              </button>
            </div>
          ) : (
            <input ref={inputRef} id={id} className="ff-input" value={typed} role="combobox"
              aria-label={`${PART_LABEL[part]} country`} aria-expanded={showList} aria-controls={`${id}-list`} aria-autocomplete="list"
              aria-activedescendant={showList && active >= 0 ? `${id}-opt-${active}` : undefined}
              onChange={e => { setTyped(e.target.value); setMaybe([]); setFocused(true) }} onFocus={() => setFocused(true)}
              onBlur={() => setFocused(false)} onKeyDown={onKey}
              placeholder={FIELD.placeholder} autoComplete={FIELD.autoComplete} autoCorrect={FIELD.autoCorrect}
              autoCapitalize={FIELD.autoCapitalize} spellCheck={FIELD.spellCheck} enterKeyHint={FIELD.enterKeyHint}
              style={{ width: "100%", height: 44, padding: "0 12px", borderRadius: 8, fontSize: 16, fontWeight: 600, color: T.text,
                background: T.bg, border: `1px solid ${T.line}` }} />
          )}
        </div>
      </div>
      {showList && (
        <ul id={`${id}-list`} role="listbox" aria-label={`${PART_LABEL[part]} suggestions`}
          style={{ listStyle: "none", margin: "8px 0 0", padding: 0, display: "flex", flexDirection: "column", gap: 4 }}>
          {options.map((c, i) => (
            <li key={c.code} id={`${id}-opt-${i}`} role="option" aria-selected={i === active}
              className="ff-tap ff-option"
              // Keep the focus in the box (so the list stays) until the click picks.
              onPointerDown={e => e.preventDefault()} onMouseDown={e => e.preventDefault()}
              onClick={() => choose(c)}
              style={{ padding: "10px 12px", borderRadius: 8, cursor: "pointer", fontSize: 15, fontWeight: 600,
                color: T.text, background: i === active ? T.surfaceHi : T.bg, border: `1px solid ${i === active ? T.lineHi : T.line}` }}>
              {c.name}
            </li>
          ))}
        </ul>
      )}
      {state === "open" && !box.pick && <DidYouMean options={maybe} onPick={choose} accent={ACC} style={{ marginLeft: 4 }} />}
      {!over && state === "open" && box.tried.length > 0 && (
        <p style={{ margin: "4px 0 0 4px", fontSize: 12, color: T.muted }}>
          Not {box.tried.map(countryName).join(", not ")}
        </p>
      )}
    </div>
  )
}

/* ── After a flag: the three real flags it was fused from. ──────────────── */
function Reveal({ fusion, result }: { fusion: Fusion; result: Played }) {
  const won = result.solved.length === PARTS.length
  const shared = PARTS.filter(p => fusion[p].accept.length > 1)
  return (
    <section className="ff-fade" aria-label="The three flags" style={{ display: "flex", flexDirection: "column", gap: 12, padding: 16, borderRadius: 16,
      background: T.surface, border: `1px solid ${tint(won ? T.green : T.danger, 0.45)}` }}>
      <div style={{ display: "flex", alignItems: "baseline", justifyContent: "space-between", gap: 12 }}>
        <span style={{ fontSize: 15, fontWeight: 700, color: won ? T.green : T.danger }}>
          {won ? (result.wrongLeft === WRONG_GUESSES ? "All three, no wrong guesses" : "All three named") : `${result.solved.length} of 3 named`}
        </span>
        <span className="geo-mono" style={{ fontSize: 14, fontWeight: 700, color: T.text }}>+{result.points}</span>
      </div>
      <div style={{ display: "grid", gridTemplateColumns: "repeat(3, minmax(0, 1fr))", gap: 8 }}>
        {PARTS.map(p => {
          const code = fusion[p].code
          const got = result.solved.includes(p)
          return (
            <figure key={p} style={{ margin: 0, display: "flex", flexDirection: "column", gap: 4, minWidth: 0 }}>
              <figcaption className="geo-micro" style={{ fontSize: 10, color: T.muted, order: -1 }}>{PART_LABEL[p]}</figcaption>
              <div style={{ aspectRatio: "4 / 3", borderRadius: 4, overflow: "hidden", border: `1px solid ${T.line}`, background: T.surfaceHi }}>
                <FlagImage code={code} style={{ width: "100%", height: "100%", objectFit: "cover", display: "block" }} />
              </div>
              <span style={{ display: "flex", alignItems: "flex-start", gap: 4, fontSize: 13, fontWeight: 700, lineHeight: 1.25, color: T.text, overflowWrap: "anywhere" }}>
                <span style={{ flexShrink: 0, marginTop: 1, color: got ? T.green : T.danger, display: "flex" }}>
                  {got ? <Check size={14} strokeWidth={2.6} aria-hidden /> : <X size={14} strokeWidth={2.6} aria-hidden />}
                </span>
                <span><span style={srOnly}>{got ? "Named: " : "Missed: "}</span>{countryName(code)}</span>
              </span>
            </figure>
          )
        })}
      </div>
      {shared.length > 0 && (
        <div style={{ display: "flex", flexDirection: "column", gap: 4 }}>
          {shared.map(p => (
            <p key={p} style={{ margin: 0, fontSize: 12, lineHeight: 1.45, color: T.muted }}>
              {p === "structure" ? "Same layout, also right: " : p === "colours" ? "Same colours, also right: " : "Also right: "}
              {fusion[p].accept.filter(c => c !== fusion[p].code).map(countryName).join(", ")}
            </p>
          ))}
        </div>
      )}
    </section>
  )
}

/* ── Result: the score, the best and every flag played. ─────────────────── */
function Result({ game, outcome, onBack, onAgain, onChange }:
  { game: Game; outcome: Outcome; onBack: () => void; onAgain: () => void; onChange: () => void }) {
  const { played, best, beat } = outcome
  const score = scoreOf(played)
  const named = played.reduce((n, p) => n + p.solved.length, 0)
  const full = played.filter(p => p.solved.length === PARTS.length).length
  const great = score >= MAX_POINTS * 0.6
  return (
    <>
      <ScreenHeader title="Flag Fusion" subtitle={`Results · ${TIER_META[game.tier].label}`} onBack={onBack} />
      <main className="w-full mx-auto flex flex-col" style={{ maxWidth: 520, padding: "4px 16px 32px", gap: 12 }}>
        <ResultCard>
          <ResultHeader icon={great ? "trophy" : "flag"} accent={great ? T.gold : ACC}
            eyebrow={beat ? "New best" : `${TIER_META[game.tier].label} · best ${best}`}
            title={`${score} points`}
            score={`${named} of ${played.length * PARTS.length} parts named · ${full} of ${played.length} flags solved`} />
          <ResultDots results={played.map(p => p.solved.length === PARTS.length)} />
        </ResultCard>

        <section aria-labelledby="ff-flags" style={{ borderRadius: 16, background: T.surface, border: `1px solid ${T.line}`, padding: "16px 16px 8px" }}>
          <h3 id="ff-flags" className="geo-micro" style={{ margin: "0 0 4px", fontSize: 11, color: T.muted }}>Your flags</h3>
          <ol style={{ listStyle: "none", margin: 0, padding: 0 }}>
            {played.map((p, i) => (
              <li key={i} style={{ display: "flex", alignItems: "center", gap: 12, padding: "12px 0", borderTop: i ? `1px solid ${T.line}` : "none" }}>
                <FusedFlag fusion={p.fusion} label={`Flag ${i + 1}`} style={{ width: 80, flexShrink: 0, boxShadow: "none" }} />
                <div style={{ flex: 1, minWidth: 0, display: "flex", flexDirection: "column", gap: 2 }}>
                  {PARTS.map(part => {
                    const got = p.solved.includes(part)
                    return (
                      <span key={part} style={{ display: "flex", alignItems: "center", gap: 6, fontSize: 13, lineHeight: 1.3, minWidth: 0 }}>
                        <span style={{ display: "flex", color: got ? T.green : T.danger, flexShrink: 0 }}>
                          {got ? <Check size={14} strokeWidth={2.6} aria-hidden /> : <X size={14} strokeWidth={2.6} aria-hidden />}
                        </span>
                        <span style={{ color: T.muted, width: 66, flexShrink: 0 }}>{PART_LABEL[part]}</span>
                        <span style={{ fontWeight: 700, color: T.text, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>{countryName(p.fusion[part].code)}</span>
                      </span>
                    )
                  })}
                </div>
                <span className="geo-mono" style={{ flexShrink: 0, fontSize: 14, fontWeight: 700, color: T.text }}>{p.points}</span>
              </li>
            ))}
          </ol>
        </section>

        <PrimaryButton accent={ACC} onClick={onAgain}>Play again</PrimaryButton>
        <SecondaryButton onClick={onChange}>Change difficulty</SecondaryButton>
      </main>
    </>
  )
}

